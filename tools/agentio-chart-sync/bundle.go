func prepareSandboxManagerValues(content []byte) ([]byte, error) {
	document := yamlv3.Node{}
	if err := yamlv3.Unmarshal(content, &document); err != nil {
		return nil, fmt.Errorf("parse source values for sandbox-manager: %w", err)
	}
	if len(document.Content) != 1 || document.Content[0].Kind != yamlv3.MappingNode {
		return nil, errors.New("source values for sandbox-manager must be a YAML mapping")
	}
	root := document.Content[0]
	setIntegrationGatewayModes(root)
	removeYAMLMappingKeys(root, "profile", "cni", "ztunnel")
	removeYAMLMappingKeys(yamlMappingValue(root, "egressGateway"), "agentgateway")
	if global := yamlMappingValue(root, "global"); global != nil {
		global.Content = append(global.Content,
			&yamlv3.Node{Kind: yamlv3.ScalarNode, Value: "namespace"}, &yamlv3.Node{Kind: yamlv3.ScalarNode, Tag: "!!str", Value: "sandbox-system"},
			&yamlv3.Node{Kind: yamlv3.ScalarNode, Value: "createNamespace"}, &yamlv3.Node{Kind: yamlv3.ScalarNode, Tag: "!!bool", Value: "true"})
	}
	if agentiod := yamlMappingValue(root, "agentiod"); agentiod != nil {
		removeYAMLMappingKeys(agentiod, "trustedNodeServiceAccount", "trustPackage", "clientTrustBundle")
		removeYAMLMappingKeys(agentiod, "injector")
	}

	var out bytes.Buffer
	encoder := yamlv3.NewEncoder(&out)
	encoder.SetIndent(2)
	if err := encoder.Encode(&document); err != nil {
		return nil, fmt.Errorf("encode sandbox-manager Agentio values: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("finish sandbox-manager Agentio values: %w", err)
	}
	return out.Bytes(), nil
}

func yamlMappingValue(mapping *yamlv3.Node, key string) *yamlv3.Node {
	if mapping == nil || mapping.Kind != yamlv3.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if mapping.Content[i].Value == key {
			return mapping.Content[i+1]
		}
	}
	return nil
}

func removeYAMLMappingKeys(mapping *yamlv3.Node, keys ...string) {
	if mapping == nil || mapping.Kind != yamlv3.MappingNode {
		return
	}
	excluded := make(map[string]struct{}, len(keys))
	for _, key := range keys {
		excluded[key] = struct{}{}
	}
	content := mapping.Content[:0]
	for i := 0; i+1 < len(mapping.Content); i += 2 {
		if _, found := excluded[mapping.Content[i].Value]; found {
			continue
		}
		content = append(content, mapping.Content[i], mapping.Content[i+1])
	}
	mapping.Content = content
}

// prepareSandboxManagerTemplate removes admission injection from the embedded
// control plane; Sandbox Pods are injected by sandbox-controller instead.
func prepareSandboxManagerTemplate(rel string, content []byte) ([]byte, error) {
	var err error
	removeBlock := func(marker string) {
		if err != nil {
			return
		}
		for {
			start := bytes.Index(content, []byte(marker))
			if start < 0 {
				return
			}
			end, blockErr := matchingDefinitionEnd(content, start)
			if blockErr != nil {
				err = fmt.Errorf("remove %s from %s: %w", marker, rel, blockErr)
				return
			}
			content = append(content[:start], content[end:]...)
		}
	}
	switch rel {
	case "agentiod/deployment.yaml":
		start := bytes.Index(content, []byte("apiVersion:"))
		if start < 0 {
			return nil, errors.New("agentiod deployment is missing apiVersion")
		}
		content = append([]byte("{{- define \"agentiod.deployment\" -}}\n"), content[start:]...)
		for _, name := range []string{"AGENTIO_TRUSTED_NODE_ACCOUNTS", "AGENTIO_INJECTOR_CONFIGMAP_NAME", "AGENTIO_INJECTION_WEBHOOK_CONFIG_NAME", "AGENTIO_NATIVE_SIDECARS"} {
			content = regexp.MustCompile(`(?m)^            - name: `+name+`\n              value: [^\n]*\n`).ReplaceAll(content, nil)
		}
		content = bytes.ReplaceAll(content, []byte("$clientTrustEnabled"), []byte("false"))
	case "agentiod/policy.yaml":
		content = bytes.ReplaceAll(
			content,
			[]byte(`dict "Values" $values`),
			[]byte(`dict "Values" (dict "agentio" $values)`),
		)
	case "_helpers.tpl":
		for _, prefix := range []string{"agentio-cni.", "ztunnel.", "agentiod.webhookName", "agentiod.componentImage", "agentio.sidecarEnabled"} {
			for {
				pattern := regexp.MustCompile(`\{\{- define "` + regexp.QuoteMeta(prefix) + `[^"\n]*"[^\n]*`)
				loc := pattern.FindIndex(content)
				if loc == nil {
					break
				}
				removeBlock(string(content[loc[0]:loc[1]]))
				if err != nil {
					break
				}
			}
		}
	}
	content = bytes.ReplaceAll(content, []byte(`{{- $_ := set $values "profile" "ambient" }}`), nil)
	removeBlock(`{{- if or (eq .Values.profile "sidecar") .Values.agentiod.injector.clientTrust.enabled }}`)
	content = bytes.ReplaceAll(
		content,
		[]byte(`(and (ne (.Values.agentiod.controlPlanePool | default "proxy") "policy") `+
			`(or (eq .Values.profile "sidecar") .Values.agentiod.injector.clientTrust.enabled))`),
		[]byte("false"),
	)
	removeBlock(`{{- if eq .Values.profile "sidecar" }}`)
	removeBlock(`{{- if eq .Values.profile "ambient" }}`)
	content = bytes.ReplaceAll(
		content,
		[]byte(`or (eq .Values.profile "sidecar") .Values.agentiod.gatewayDeployer.enabled`),
		[]byte(`.Values.agentiod.gatewayDeployer.enabled`),
	)
	content = bytes.ReplaceAll(content, []byte(`(eq .Values.profile "sidecar")`), []byte("false"))
	content = bytes.ReplaceAll(content, []byte(`eq .Values.profile "sidecar"`), []byte("false"))
	content = bytes.ReplaceAll(content, []byte(`eq .Values.profile "ambient"`), []byte("false"))
	if err != nil {
		return nil, err
	}
	for _, forbidden := range []string{".Values.profile", ".Values.cni", ".Values.ztunnel", "mutatingwebhookconfigurations", "$useTrustPackage"} {
		if bytes.Contains(content, []byte(forbidden)) {
			return nil, fmt.Errorf("sandbox-manager template %q retains unsupported capability %q", rel, forbidden)
		}
	}
	return regexp.MustCompile(`(?m)[ \t]+$`).ReplaceAll(content, nil), nil
}

func validatePreparedBlock(content []byte, beginMarker, endMarker, description string) error {
	block, err := extractMarkedBlock(content, beginMarker, endMarker, description)
	if err != nil {
		return err
	}
	if !bytes.Equal(bytes.TrimSpace(content), bytes.TrimSpace(block)) {
		return fmt.Errorf("%s must contain only its generated marker block", description)
	}
	return nil
}

func extractMarkedBlock(content []byte, beginMarker, endMarker, description string) ([]byte, error) {
	beginCount := bytes.Count(content, []byte(beginMarker))
	endCount := bytes.Count(content, []byte(endMarker))
	if beginCount != 1 || endCount != 1 {
		return nil, fmt.Errorf("%s must contain exactly one matching marker pair", description)
	}
	begin := bytes.Index(content, []byte(beginMarker))
	end := bytes.Index(content, []byte(endMarker))
	if begin > end {
		return nil, fmt.Errorf("%s markers are out of order", description)
	}
	end += len(endMarker)
	if end < len(content) && content[end] == '\r' {
		end++
	}
	if end < len(content) && content[end] == '\n' {
		end++
	}
	return append([]byte(nil), content[begin:end]...), nil
}

func replaceMarkedBlock(target, block []byte, beginMarker, endMarker, description string) ([]byte, error) {
	beginCount := bytes.Count(target, []byte(beginMarker))
	endCount := bytes.Count(target, []byte(endMarker))
	if beginCount == 0 && endCount == 0 {
		var err error
		target, err = prepareValuesAppend(target, description)
		if err != nil {
			return nil, err
		}

		out := append([]byte(nil), target...)
		if len(out) > 0 && out[len(out)-1] != '\n' {
			out = append(out, '\n')
		}
		if len(out) > 0 && !bytes.HasSuffix(out, []byte("\n\n")) {
			out = append(out, '\n')
		}
		return append(out, block...), nil
	}
	if beginCount != 1 || endCount != 1 {
		return nil, fmt.Errorf("%s must contain exactly one matching marker pair", description)
	}
	begin := bytes.Index(target, []byte(beginMarker))
	end := bytes.Index(target, []byte(endMarker))
	if begin > end {
		return nil, fmt.Errorf("%s markers are out of order", description)
	}
	end += len(endMarker)
	if end < len(target) && target[end] == '\r' {
		end++
	}
	if end < len(target) && target[end] == '\n' {
		end++
	}

	out := make([]byte, 0, begin+len(block)+len(target)-end)
	out = append(out, target[:begin]...)
	out = append(out, block...)
	out = append(out, target[end:]...)
	return out, nil
}

func prepareValuesAppend(target []byte, description string) ([]byte, error) {
	var document yamlv3.Node
	if err := yamlv3.Unmarshal(target, &document); err != nil {
		return nil, fmt.Errorf("parse %s: %w", description, err)
	}
	if len(document.Content) > 0 {
		root := document.Content[0]
		if root.Kind != yamlv3.MappingNode {
			return nil, fmt.Errorf("%s must be a YAML mapping", description)
		}
		if yamlMappingValue(root, "agentio") != nil {
			return nil, fmt.Errorf("%s contains unmarked agentio values", description)
		}
		if root.Style&yamlv3.FlowStyle != 0 {
			if len(root.Content) == 0 {
				target = nil
			} else {
				root.Style &^= yamlv3.FlowStyle
				var out bytes.Buffer
				encoder := yamlv3.NewEncoder(&out)
				encoder.SetIndent(2)
				if err := encoder.Encode(&document); err != nil {
					return nil, err
				}
				if err := encoder.Close(); err != nil {
					return nil, err
				}
				target = out.Bytes()
			}
		}
	}
	return target, nil
}

