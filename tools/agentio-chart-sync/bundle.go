func generatedTrafficProxyBlock(template []byte) []byte {
	template = bytes.TrimSuffix(template, []byte("\n"))
	var out bytes.Buffer
	fmt.Fprintln(&out, "  traffic-proxy: |")
	for _, line := range bytes.Split(template, []byte("\n")) {
		if len(line) > 0 {
			out.WriteString("    ")
			out.Write(line)
		}
		out.WriteByte('\n')
	}
	return out.Bytes()
}

func newSandboxInjectionConfigTemplate(block []byte) []byte {
	var out bytes.Buffer
	fmt.Fprintln(&out, "apiVersion: v1")
	fmt.Fprintln(&out, "kind: ConfigMap")
	fmt.Fprintln(&out, "metadata:")
	fmt.Fprintln(&out, "  name: sandbox-injection-config")
	fmt.Fprintln(&out, "  namespace: {{ include \"sandbox-controller.namespace\" . }}")
	fmt.Fprintln(&out, "data:")
	out.Write(block)
	return out.Bytes()
}

var sandboxInjectionConfigNamePattern = regexp.MustCompile(`(?m)^[ \t]*name:[ \t]*["']?sandbox-injection-config["']?[ \t]*\r?$`)
var yamlDataLinePattern = regexp.MustCompile(`(?m)^data:[ \t]*\r?\n`)
var yamlTrafficProxyLinePattern = regexp.MustCompile(`(?m)^  traffic-proxy:[^\r\n]*(?:\r?\n|$)`)

func findSandboxInjectionConfigTemplate(templates string) (string, []byte, error) {
	var foundPath string
	var foundContent []byte
	err := filepath.WalkDir(templates, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("sandbox-controller template %q is a symlink", path)
		}
		ext := strings.ToLower(filepath.Ext(path))
		if ext != ".yaml" && ext != ".yml" {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !sandboxInjectionConfigNamePattern.Match(content) {
			return nil
		}
		if foundPath != "" {
			return fmt.Errorf("multiple sandbox-injection-config templates found: %q and %q", foundPath, path)
		}
		foundPath = path
		foundContent = content
		return nil
	})
	if err != nil {
		return "", nil, fmt.Errorf("find sandbox injection ConfigMap template: %w", err)
	}
	return foundPath, foundContent, nil
}

func mergeTrafficProxyBlock(content, block []byte) ([]byte, error) {
	content = removeLegacyControllerWholeFileWarning(content)
	beginCount := bytes.Count(content, []byte(trafficProxyBegin))
	endCount := bytes.Count(content, []byte(trafficProxyEnd))
	if beginCount != 0 || endCount != 0 {
		if beginCount != 1 || endCount != 1 {
			return nil, errors.New("template must contain exactly one matching Agentio traffic-proxy marker pair")
		}
		begin := bytes.Index(content, []byte(trafficProxyBegin))
		end := bytes.Index(content, []byte(trafficProxyEnd))
		if begin > end {
			return nil, errors.New("Agentio traffic-proxy template markers are out of order")
		}
		end += len(trafficProxyEnd)
		if end < len(content) && content[end] == '\r' {
			end++
		}
		if end < len(content) && content[end] == '\n' {
			end++
		}
		out := make([]byte, 0, begin+len(block)+len(content)-end)
		out = append(out, content[:begin]...)
		out = append(out, block...)
		out = append(out, content[end:]...)
		return out, nil
	}

	name := sandboxInjectionConfigNamePattern.FindIndex(content)
	if name == nil {
		return nil, errors.New("sandbox-injection-config metadata.name not found")
	}
	documentStart := bytes.LastIndex(content[:name[0]], []byte("\n---"))
	if documentStart < 0 {
		documentStart = 0
	} else {
		documentStart += len("\n---")
	}
	documentEndRelative := bytes.Index(content[name[1]:], []byte("\n---"))
	documentEnd := len(content)
	if documentEndRelative >= 0 {
		documentEnd = name[1] + documentEndRelative
	}
	document := content[documentStart:documentEnd]
	data := yamlDataLinePattern.FindIndex(document)
	if data != nil {
		insert := documentStart + data[1]
		if existing := yamlTrafficProxyLinePattern.FindIndex(content[insert:documentEnd]); existing != nil {
			entryStart := insert + existing[0]
			entryEnd := yamlEntryEnd(content, insert+existing[1], documentEnd, 2)
			out := make([]byte, 0, len(content)-entryEnd+entryStart+len(block))
			out = append(out, content[:entryStart]...)
			out = append(out, block...)
			out = append(out, content[entryEnd:]...)
			return out, nil
		}
		out := make([]byte, 0, len(content)+len(block))
		out = append(out, content[:insert]...)
		out = append(out, block...)
		out = append(out, content[insert:]...)
		return out, nil
	}

	insert := documentEnd
	var addition bytes.Buffer
	if insert > 0 && content[insert-1] != '\n' {
		addition.WriteByte('\n')
	}
	fmt.Fprintln(&addition, "data:")
	addition.Write(block)
	out := make([]byte, 0, len(content)+addition.Len())
	out = append(out, content[:insert]...)
	out = append(out, addition.Bytes()...)
	out = append(out, content[insert:]...)
	return out, nil
}

func removeLegacyControllerWholeFileWarning(content []byte) []byte {
	for _, legacyWarning := range [][]byte{
		[]byte(warning),
		[]byte("{{/* Code generated by agentio-chart-exporter. DO NOT EDIT. */}}\n"),
	} {
		if bytes.HasPrefix(content, legacyWarning) {
			return content[len(legacyWarning):]
		}
	}
	return content
}

func extractTrafficProxyBlock(content []byte, description string) ([]byte, error) {
	name := sandboxInjectionConfigNamePattern.FindIndex(content)
	if name == nil {
		return nil, fmt.Errorf("%s metadata.name not found", description)
	}
	documentStart := bytes.LastIndex(content[:name[0]], []byte("\n---"))
	if documentStart < 0 {
		documentStart = 0
	} else {
		documentStart += len("\n---")
	}
	documentEndRelative := bytes.Index(content[name[1]:], []byte("\n---"))
	documentEnd := len(content)
	if documentEndRelative >= 0 {
		documentEnd = name[1] + documentEndRelative
	}
	document := content[documentStart:documentEnd]
	data := yamlDataLinePattern.FindIndex(document)
	if data == nil {
		return nil, fmt.Errorf("%s data mapping not found", description)
	}
	dataStart := documentStart + data[1]
	entry := yamlTrafficProxyLinePattern.FindIndex(content[dataStart:documentEnd])
	if entry == nil {
		return nil, fmt.Errorf("%s data.traffic-proxy entry not found", description)
	}
	entryStart := dataStart + entry[0]
	entryEnd := yamlEntryEnd(content, dataStart+entry[1], documentEnd, 2)
	return append([]byte(nil), content[entryStart:entryEnd]...), nil
}

func yamlEntryEnd(content []byte, start, limit, indentation int) int {
	for offset := start; offset < limit; {
		lineEnd := bytes.IndexByte(content[offset:limit], '\n')
		next := limit
		if lineEnd >= 0 {
			next = offset + lineEnd + 1
		}
		line := bytes.TrimSuffix(content[offset:next], []byte("\n"))
		line = bytes.TrimSuffix(line, []byte("\r"))
		if len(bytes.TrimSpace(line)) > 0 {
			leading := len(line) - len(bytes.TrimLeft(line, " \t"))
			if leading <= indentation {
				return offset
			}
		}
		offset = next
	}
	return limit
}

