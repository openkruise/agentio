// ExportSandboxController installs an already prepared traffic-proxy entry
// without replacing other sandbox runtime injection entries.
func ExportSandboxController(source, target string) error {
	sourceValues, err := os.ReadFile(filepath.Join(source, "values.yaml"))
	if err != nil {
		return fmt.Errorf("read prepared sandbox-controller values: %w", err)
	}
	if err := validatePreparedBlock(sourceValues, controllerValuesBegin, controllerValuesEnd, "sandbox-controller values"); err != nil {
		return err
	}
	targetValuesPath := filepath.Join(target, "values.yaml")
	targetValues, err := os.ReadFile(targetValuesPath)
	if err != nil {
		return fmt.Errorf("read sandbox-controller values: %w", err)
	}
	nextValues, err := replaceMarkedBlock(targetValues, sourceValues, controllerValuesBegin, controllerValuesEnd, "sandbox-controller values")
	if err != nil {
		return err
	}

	bundleTemplatePath, bundleTemplate, err := findSandboxInjectionConfigTemplate(filepath.Join(source, "templates"))
	if err != nil {
		return err
	}
	if bundleTemplate == nil {
		return errors.New("prepared sandbox-controller bundle does not contain sandbox-injection-config")
	}
	block, err := extractTrafficProxyBlock(bundleTemplate, "prepared traffic-proxy template")
	if err != nil {
		return err
	}
	targetTemplatePath, existing, err := findSandboxInjectionConfigTemplate(filepath.Join(target, "templates"))
	if err != nil {
		return err
	}
	var nextTemplate []byte
	if existing == nil {
		targetTemplatePath = filepath.Join(target, "templates", filepath.Base(bundleTemplatePath))
		nextTemplate = bundleTemplate
	} else {
		nextTemplate, err = mergeTrafficProxyBlock(existing, block)
		if err != nil {
			return fmt.Errorf("update sandbox injection ConfigMap %q: %w", targetTemplatePath, err)
		}
	}

	if err := os.MkdirAll(filepath.Dir(targetTemplatePath), 0o755); err != nil {
		return fmt.Errorf("create sandbox-controller template directory: %w", err)
	}
	if err := writeFileAtomically(targetTemplatePath, nextTemplate, 0o644); err != nil {
		return fmt.Errorf("write sandbox injection ConfigMap: %w", err)
	}
	if err := writeFileAtomically(targetValuesPath, nextValues, 0o644); err != nil {
		return fmt.Errorf("write sandbox-controller values: %w", err)
	}
	return nil
}

// buildSandboxControllerBundle prepares the traffic-proxy integration source
// from the standalone Agentio chart.
func buildSandboxControllerBundle(source, target string) error {
	sourceValues, err := os.ReadFile(filepath.Join(source, "values.yaml"))
	if err != nil {
		return fmt.Errorf("read source values for sandbox-controller: %w", err)
	}
	controllerValues, err := generatedSandboxControllerValuesBlock(sourceValues)
	if err != nil {
		return err
	}
	targetValuesPath := filepath.Join(target, "values.yaml")
	targetValues, err := os.ReadFile(targetValuesPath)
	if err != nil {
		return fmt.Errorf("read sandbox-controller values: %w", err)
	}
	nextValues, err := replaceSandboxControllerValuesBlock(targetValues, controllerValues)
	if err != nil {
		return err
	}

	templatePath := filepath.Join(source, "files", trafficProxyTemplateFile)
	template, err := os.ReadFile(templatePath)
	if err != nil {
		return fmt.Errorf("read Kruise Agents traffic-proxy template: %w", err)
	}
	block := generatedTrafficProxyBlock(template)
	targetTemplatePath, existing, err := findSandboxInjectionConfigTemplate(filepath.Join(target, "templates"))
	if err != nil {
		return err
	}
	var nextTemplate []byte
	if existing == nil {
		targetTemplatePath = filepath.Join(target, "templates", generatedInjectionConfigFile)
		nextTemplate = newSandboxInjectionConfigTemplate(block)
	} else {
		nextTemplate, err = mergeTrafficProxyBlock(existing, block)
		if err != nil {
			return fmt.Errorf("update sandbox injection ConfigMap %q: %w", targetTemplatePath, err)
		}
	}

	if err := os.MkdirAll(filepath.Dir(targetTemplatePath), 0o755); err != nil {
		return fmt.Errorf("create sandbox-controller template directory: %w", err)
	}
	if err := writeFileAtomically(targetTemplatePath, nextTemplate, 0o644); err != nil {
		return fmt.Errorf("write sandbox injection ConfigMap: %w", err)
	}
	if err := writeFileAtomically(targetValuesPath, nextValues, 0o644); err != nil {
		return fmt.Errorf("write sandbox-controller values: %w", err)
	}
	return nil
}

func generatedSandboxControllerValuesBlock(content []byte) ([]byte, error) {
	values := sandboxControllerSourceValues{}
	if err := yaml.Unmarshal(content, &values); err != nil {
		return nil, fmt.Errorf("parse source values for sandbox-controller: %w", err)
	}
	resolve := func(image, name string) (string, error) {
		if image != "" {
			return image, nil
		}
		return resolveChartImage(values.Global.Hub, values.Global.Tag, chartImageValues{Name: name})
	}
	ztunnelImage, err := resolve(values.Agentiod.Injector.Ztunnel.Image, values.Agentiod.Injector.Ztunnel.ImageName)
	if err != nil {
		return nil, fmt.Errorf("resolve ztunnel image: %w", err)
	}
	proxyInitImage, err := resolve(values.Agentiod.Injector.ProxyInit.Image, values.Agentiod.Injector.ProxyInit.ImageName)
	if err != nil {
		return nil, fmt.Errorf("resolve proxy-init image: %w", err)
	}
	service := values.Agentiod.FullnameOverride
	if service == "" {
		service = values.Agentiod.NameOverride
	}
	if service == "" {
		service = "agentiod"
	}
	service = strings.TrimRight(truncateName(service), "-")

	priority := values.Agentiod.Injector.ProxyInit.NATOutputPriority
	if priority == "" {
		priority = "-100"
	}
	generated := map[string]any{
		"agentio": map[string]any{
			"sandbox": map[string]any{"enabled": values.Sandbox.Enabled},
			"trafficProxy": map[string]any{
				"controlPlaneNamespace":   "sandbox-system",
				"controlPlaneService":     service,
				"xdsAddress":              "",
				"clusterDomain":           values.Global.ClusterDomain,
				"tokenAudience":           values.Agentiod.TokenAudience,
				"enableFirewallRules":     values.Agentiod.Injector.Ztunnel.EnableFirewallRules,
				"firewallBackend":         values.Agentiod.Injector.Ztunnel.FirewallBackend,
				"caAddress":               "",
				"caCertConfigMap":         values.Agentiod.CA.TrustBundleConfigMapName,
				"clusterId":               values.Global.ClusterID,
				"image":                   ztunnelImage,
				"initImage":               proxyInitImage,
				"imagePullPolicy":         values.Global.ImagePullPolicy,
				"healthProbeRewrite":      true,
				"dnsCapture":              true,
				"nativeNftables":          values.Agentiod.Injector.ProxyInit.NativeNftables,
				"natOutputPriority":       priority,
				"rejectNonTCP":            values.Agentiod.Injector.ProxyInit.RejectNonTCP,
				"includeOutboundIPRanges": "*",
				"excludeOutboundIPRanges": "",
				"includeInboundPorts":     "*",
				"excludeInboundPorts":     "",
				"includeOutboundPorts":    "",
				"excludeOutboundPorts":    "",
				"resources": map[string]any{
					"requests": map[string]string{"cpu": "100m", "memory": "64Mi"},
					"limits":   map[string]string{"cpu": "200m", "memory": "128Mi"},
				},
				"initResources": map[string]any{
					"requests": map[string]string{"cpu": "100m", "memory": "128Mi"},
					"limits":   map[string]string{"cpu": "1", "memory": "1Gi"},
				},
			},
		},
	}
	encoded, err := yaml.Marshal(generated)
	if err != nil {
		return nil, fmt.Errorf("marshal sandbox-controller Agentio values: %w", err)
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, controllerValuesBegin)
	out.Write(encoded)
	fmt.Fprintln(&out, controllerValuesEnd)
	return out.Bytes(), nil
}

func truncateName(name string) string {
	if len(name) > 63 {
		return name[:63]
	}
	return name
}

func resolveChartImage(globalHub, globalTag string, image chartImageValues) (string, error) {
	repository := image.Repository
	if image.Digest != "" {
		if repository == "" {
			return "", errors.New("repository is required when digest is set")
		}
		return repository + "@" + image.Digest, nil
	}
	if repository == "" {
		if globalHub == "" || image.Name == "" {
			return "", errors.New("hub and name must be non-empty")
		}
		repository = strings.TrimSuffix(globalHub, "/") + "/" + strings.TrimPrefix(image.Name, "/")
	}
	tag := image.Tag
	if tag == "" {
		tag = globalTag
	}
	if tag == "" {
		return "", errors.New("image tag must be non-empty")
	}
	return repository + ":" + tag, nil
}

